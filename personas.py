def get(name: str, profanity: str, custom: str = ""):
    p = dict(PERSONAS.get(name, PERSONAS["default"]))
    if name == "custom":
        p["prompt"] = custom or PERSONAS["default"]["prompt"]
    p["prompt"] = p["prompt"] + " " + PROFANITY.get(profanity, PROFANITY["none"])
    return p
